#!/usr/bin/env python3
"""Regenerate the GIF tag index in both forms the two frontends can read.

The tagged GIF pack encodes its metadata in filenames:
    <name>_<tag>_<tag>...gif      e.g. disc_ps1_ps2_dc_sat.gif
Tags are console shortnames (nes, snes, ps1, arcade, ...) or the literal
"all" for something that fits anywhere.

Two outputs, one source of truth:
  gif-index.json — read by the web control plane via fetch()
  gif-index.js   — imported by the Pegasus QML theme

The QML copy is NOT a convenience. Qt 5.15 refuses XMLHttpRequest on local
files unless QML_XHR_ALLOW_FILE_READ=1, which we cannot set for the Pegasus
process, so a theme that fetched the JSON would silently render no mascots on
the cabinet. Importing a .js library has no such restriction.

The pack itself is drawn by generate-sprites.py. Run after adding or
removing GIFs:
    python3 assets/build-gif-index.py
"""
import json
import pathlib
import struct

HERE = pathlib.Path(__file__).resolve().parent
GIFS = HERE / "gifs"

# Blend hints, carried over from the design pack: 0 = plain sprite (drop
# shadow), 1 = multiply (art baked on a white background), 2 = framed sticker.
BLEND = {}  # the generated pack is all transparent sprites (0)


def gif_size(path):
    """Width/height straight out of the GIF logical screen descriptor.

    Avoids a Pillow dependency for what is six bytes at a fixed offset; every
    GIF87a/89a puts them there.
    """
    with open(path, "rb") as f:
        head = f.read(10)
    if head[:3] != b"GIF":
        raise ValueError(f"{path.name} is not a GIF")
    return struct.unpack("<HH", head[6:10])


def parse_tags(stem):
    """'disc_ps1_ps2_dc_sat' -> ('disc', ['ps1','ps2','dc','sat'])."""
    parts = stem.split("_")
    tags, name = [], []
    for part in reversed(parts):
        # tags are a suffix run; the first non-tag token ends it
        if part in KNOWN_TAGS and not name:
            tags.insert(0, part)
        else:
            name.insert(0, part)
    return " ".join(name) or stem, tags


KNOWN_TAGS = {
    "all", "nes", "snes", "n64", "ngc", "wii", "wiiu", "nds", "3ds", "nsw",
    "gb", "gbc", "gba", "gen", "sms", "gg", "sat", "dc", "ps1", "ps2", "ps3",
    "ps4", "ps5", "psp", "psv", "xbox", "x360", "xone", "xsx", "pc", "arcade",
    "msx2",
}


def main():
    out = []
    for path in sorted(GIFS.glob("*.gif")):
        w, h = gif_size(path)
        name, tags = parse_tags(path.stem)
        out.append({"file": path.name, "name": name, "tags": tags,
                    "w": w, "h": h, "blend": BLEND.get(path.name, 0)})

    doc = {"schemaVersion": 1,
           "blendModes": {"0": "normal", "1": "multiply", "2": "framed"},
           "gifs": out}
    (HERE / "gif-index.json").write_text(json.dumps(doc, indent=1) + "\n")

    js = ["// GENERATED by assets/build-gif-index.py — do not edit by hand.",
          "// Imported by themes/pegasus-y2k/theme.qml. See that script for why",
          "// this exists alongside gif-index.json.",
          ".pragma library",
          "var GIFS = " + json.dumps(out, indent=1) + ";",
          ""]
    (HERE / "gif-index.js").write_text("\n".join(js))
    print(f"indexed {len(out)} gifs -> gif-index.json + gif-index.js")


if __name__ == "__main__":
    main()
